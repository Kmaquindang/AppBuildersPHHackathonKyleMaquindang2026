// ExecutiveAssistant.swift
// Pasa: the team's executive assistant. Runs on the Mac AI peer, all local.
//
// Flow for every "@pasa ..." / Ask AI message:
// 1. Fast path for common phrases (no model call). Plain questions with no command words
//    (QuestionRouter) skip classification and go straight to the answer call. Everything else
//    gets one JSON-mode model call that classifies the intent and extracts fields.
// 2. The intent is applied to OrgMemory (the source of truth) with its permission rules.
// 3. When needed, a second model call writes the reply (grounded answers, catch-up, notes).
// 4. Answers are styled for chat (AnswerStyle): citation tags leave the text and travel as
//    structured rule chips (rulesUsed / unverifiedRules / noRule).
// 5. The reply is compacted for the mesh; the rest is kept for "@pasa more".
// Task and rule changes are returned so the mesh layer can notify assignees and phones.

import Foundation

public struct AssistantOutcome: Sendable {
    public var intent: IntentKind
    public var reply: String
    public var compact: Bool
    /// Model that produced the reply, nil when no model call was needed.
    public var model: String?
    public var latencyMs: Int
    public var tokensPerSecond: Double?
    public var evalCount: Int?
    public var modelCalls: Int
    /// Tasks created or changed: send each to its assignee device.
    public var taskUpdates: [TaskItem]
    /// Rules created or changed: broadcast a summary so phones cache it.
    public var ruleUpdates: [RuleEntry]
    public var error: String?
    /// Rule and note titles shown to the model for an answer (empty when none were relevant).
    public var checked: [String] = []
    /// Estimated prompt tokens of the largest model call (about 4 characters per token).
    public var promptTokensEstimate: Int?
    /// Prompt tokens Ollama reported reading (prompt_eval_count) for that call.
    public var promptEvalCount: Int?
    /// The whole reply before it was cut to the first mesh packet (benchmark scoring).
    public var fullReply: String? = nil
    /// "@pasa summary": the digest the Mac should send to the whole room as a summary card.
    public var digest: DailyDigest? = nil
    /// Tokens generated by all model calls of this ask.
    public var evalTokens: Int? = nil
    /// Saved rules and notes this reply relied on or changed (exact current citations). The
    /// phone shows them as chips under the bubble; the text itself carries no tags.
    public var rulesUsed: [String] = []
    /// Citation tags the model wrote that name nothing saved (warning chip, never a rule).
    public var unverifiedRules: [String] = []
    /// Answers only: no saved rule or note backs this answer. nil for other intents.
    public var noRule: Bool? = nil
    /// Answers only: Knowledge passages the reply used (validated [Doc N] tags).
    public var docRefs: [DocRef] = []
    /// True when the intent model call was skipped (plain question or fast path).
    public var skippedClassify = false
}

@MainActor
public final class ExecutiveAssistant {
    /// Team memory of the active room. Swapped when the Mac switches rooms (see switchRoom).
    public private(set) var memory: OrgMemory
    public var llm: any LLMClient
    /// This Mac's mesh name (always an admin).
    public var selfName: String
    /// Person -> device, for example "Ana" -> "iPhone 12".
    public var roster: [String: String]
    /// Devices currently or recently seen on the mesh.
    public var knownDevices: [String]
    /// Device id -> chosen display name ("iPhone 12" -> "Ana"), learned from messages.
    public var directory: [String: String] = [:]
    public var chatContextLimit = 30
    /// Most lines a "since you were away" catch-up reads.
    public var sinceContextLimit = 60
    /// The Mac cleared the team timeline at this time: catch-ups never include older chat.
    public var clearedAt: Date?

    /// "@pasa more" text, keyed by room and asker so rooms never see each other's leftovers.
    private var pendingMore: [String: String] = [:]
    /// Room the next handle() call answers in (multi-room AI Mac).
    public private(set) var roomKey = ""
    /// Label of that room ("BOHOL-7"), for summary cards.
    public var roomLabel = ""
    /// Local calendar for "today" (device time zone; tests pin Asia/Manila).
    public var calendar = Calendar.current
    /// Clock for summaries (tests use a fixed time).
    public var now: () -> Date = { Date() }
    public var digestSchedule = DigestSchedule.standard
    /// num_ctx Pasa asks Ollama for; compaction starts above 75% of it (tests use a small one).
    public var contextTokens = PromptBudget.contextTokens
    /// Knowledge (room library) for the room being served; nil or empty means no documents.
    public var library: LibraryIndex? = nil
    /// Embedding model for hybrid search; nil means keyword-only.
    public var embedder: (any Embedder)? = nil
    /// Last answer's Knowledge search: hits shown, whether vectors were used (Proof panel, harness).
    public private(set) var lastLibrarySearch: (hits: Int, hybrid: Bool) = (0, false)
    /// Per room: context fill of the last answer, last compaction, summary size (Mac Proof panel).
    public private(set) var contextStats: [String: ContextStats] = [:]

    /// Room switch: ground on the new room's memory only, and forget "more" text from the old one.
    public func switchRoom(memory newMemory: OrgMemory, clearedAt newClearedAt: Date?) {
        memory = newMemory
        clearedAt = newClearedAt
        pendingMore.removeAll()
    }

    /// Multi-room AI Mac: answer the next ask from this room's memory. Keeps every room's
    /// pending "more" text (keyed by room and asker).
    public func serve(room: String, memory newMemory: OrgMemory, clearedAt newClearedAt: Date?) {
        roomKey = room
        memory = newMemory
        clearedAt = newClearedAt
    }

    private func moreKey(_ asker: String) -> String { roomKey + "|" + asker }

    public init(memory: OrgMemory, llm: any LLMClient, selfName: String, roster: [String: String] = [:], knownDevices: [String] = []) {
        self.memory = memory
        self.llm = llm
        self.selfName = selfName
        self.roster = roster
        self.knownDevices = knownDevices
    }

    var people: [String] {
        var names = Array(roster.keys) + Array(directory.values).sorted() + knownDevices + [selfName]
        names = names.filter { !$0.isEmpty }
        var seen = Set<String>()
        return names.filter { seen.insert($0).inserted }
    }

    /// Resolves a spoken assignee to (display name, device).
    /// Order: "me", the manual roster (optional override), people's chosen display names
    /// (case-insensitive exact, must be unique), then fuzzy device names.
    public func resolveAssignee(_ raw: String?, asker: String) -> (name: String?, device: String?) {
        guard let raw = raw?.nilIfBlank else { return (nil, nil) }
        let lowered = raw.lowercased()
        if ["me", "i", "myself", "sender"].contains(lowered) {
            return (directory[asker] ?? asker, asker)
        }
        let rosterExact = roster.keys.first { NameMatcher.normalize($0) == NameMatcher.normalize(raw) }
        if let key = rosterExact { return (key, roster[key]) }
        switch PeopleDirectory.resolve(raw, directory: directory) {
        case .device(let name, let device): return (name, device)
        case .ambiguous(let name, _): return (name, nil)
        case .none: break
        }
        if let rosterKey = NameMatcher.match(raw, in: Array(roster.keys)) {
            return (rosterKey, roster[rosterKey])
        }
        if let device = NameMatcher.match(raw, in: knownDevices + [selfName]) {
            return (device, device)
        }
        return (raw, nil)
    }

    // MARK: Entry point

    /// - Parameter since: the asker was away from this time on (sent by the phone with the ask).
    ///   "What did I miss" then summarizes only chat after it. nil means a plain recap.
    /// - Parameter askID: the ask's id (askKey); names the thread turn this exchange becomes.
    /// - Parameter onPartial: raw model text as it is written, for streamed answers (issue #2).
    ///   Called only for grounded answers and only when the client streams; the returned outcome
    ///   is still the whole, checked answer.
    public func handle(_ rawText: String, from asker: String, since: Date? = nil, askID: UUID? = nil,
                       onPartial: (@Sendable (String) -> Void)? = nil) async -> AssistantOutcome {
        var outcome = await handleCore(rawText, from: asker, since: since, onPartial: onPartial)
        recordTurn(question: rawText, outcome: &outcome, asker: asker, askID: askID)
        return outcome
    }

    /// Saves the exchange in this room's thread (not "more", summaries or photo prompts, and not
    /// failures), so the next answer can see it.
    private func recordTurn(question: String, outcome: inout AssistantOutcome, asker: String, askID: UUID?) {
        guard outcome.error == nil, ![.more, .dailySummary, .describePhoto].contains(outcome.intent) else { return }
        let text = question.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { return }
        let answer = outcome.fullReply ?? outcome.reply
        memory.recordTurn(ThreadTurn(id: askID ?? UUID(), asker: asker, askerName: directory[asker] ?? asker,
                                     question: text, answer: answer, at: now()))
        if var stats = contextStats[roomKey] {
            stats.totalTurns = memory.threadTurns.count
            contextStats[roomKey] = stats
        }
    }

    /// Thread context for an answer: summary, verbatim turns, recalled older lines.
    private func conversation(for question: String, asker: String, keep: Int = ConversationMemory.maxVerbatimTurns,
                              withRecall: Bool = true) -> ConversationContext {
        let all = memory.threadTurns
        let uncovered = ConversationMemory.uncovered(all, summary: memory.roomSummary, clearedAt: clearedAt)
        let verbatim = ConversationMemory.verbatim(uncovered, asker: asker, limit: keep)
        let ids = Set(verbatim.map(\.id))
        let older = all.filter { !ids.contains($0.id) }
        let recalled = withRecall
            ? ConversationMemory.recall(question: question, chat: memory.archivedChat() + memory.snapshot.chatLog, olderTurns: older,
                                        now: now(), calendar: calendar, clearedAt: clearedAt)
            : []
        let summary = memory.roomSummary.map(\.text)
        return ConversationContext(summary: (summary ?? "").isEmpty ? nil : summary, turns: verbatim, recalled: recalled)
    }

    /// Folds the oldest uncovered turns (all but the newest 4) and the previous summary into a new
    /// "room so far" summary: one model call. Returns false when there was nothing to fold or the
    /// call failed (the answer then goes ahead with a trimmed thread).
    @discardableResult
    func compactThread(tracker: inout CallTracker) async -> Bool {
        let uncovered = ConversationMemory.uncovered(memory.threadTurns, summary: memory.roomSummary, clearedAt: clearedAt)
        let fold = ConversationMemory.toCompact(uncovered)
        guard let first = fold.first, let last = fold.last else { return false }
        let previous = memory.roomSummary
        let turns: [ChatTurn] = [
            .system(ConversationMemory.summarySystem),
            .user(ConversationMemory.summaryUser(previous: previous?.text, turns: fold, calendar: calendar))
        ]
        do {
            let result = try await llm.chat(turns, json: false, maxTokens: TokenCaps.summarize)
            tracker.add(result, prompt: turns)
            let text = ConversationMemory.cleanSummary(result.text)
            guard !text.isEmpty else { return false }
            let at = now()
            memory.setRoomSummary(RoomSummary(text: text, updatedAt: at,
                                              firstTurn: previous?.firstTurn ?? first.id, lastTurn: last.id,
                                              turnCount: (previous?.turnCount ?? 0) + fold.count,
                                              coveredFrom: previous?.coveredFrom ?? first.at, coveredTo: last.at))
            return true
        } catch {
            return false
        }
    }

    private func handleCore(_ rawText: String, from asker: String, since: Date? = nil,
                            onPartial: (@Sendable (String) -> Void)? = nil) async -> AssistantOutcome {
        let started = Date()
        var tracker = CallTracker()
        let text = rawText.trimmingCharacters(in: .whitespacesAndNewlines)

        // 1. Plan
        var plan: AssistantPlan
        var skippedClassify = false
        if let fast = IntentParser.fastPath(text) {
            plan = fast
            skippedClassify = true
        } else if QuestionRouter.isPlainQuestion(text) {
            plan = AssistantPlan(kind: .answer, question: text)
            skippedClassify = true
        } else {
            do {
                let turns: [ChatTurn] = [
                    .system(AssistantPrompts.classify(rules: memory.rules, people: people, openTasks: memory.openTasks)),
                    .user(AssistantPrompts.classifyUser(text: text, asker: asker))
                ]
                let result = try await llm.chat(turns, json: true, maxTokens: TokenCaps.classify)
                tracker.add(result, prompt: turns)
                plan = IntentParser.decodePlan(from: result.text, original: text)
            } catch {
                return failure(error, intent: .answer, started: started, tracker: tracker)
            }
        }

        // 2 and 3. Act, then reply
        var reply = ""
        var taskUpdates: [TaskItem] = []
        var ruleUpdates: [RuleEntry] = []
        var checked: [String] = []
        var rulesUsed: [String] = []
        var unverifiedRules: [String] = []
        var noRule: Bool? = nil
        var docRefs: [DocRef] = []

        switch plan.kind {
        case .dailySummary:
            let at = now()
            let digest = await DigestWriter.make(room: roomKey, label: roomLabel.isEmpty ? "this room" : roomLabel, snapshot: memory.snapshot,
                                                 day: DigestClock.dayKey(at, calendar: calendar), interval: DigestClock.dayInterval(of: at, calendar: calendar),
                                                 scheduled: false, late: false, llm: llm, now: at, calendar: calendar,
                                                 directory: directory, schedule: digestSchedule)
            var outcome = finish(digest.text, intent: .dailySummary, started: started, tracker: tracker, asker: asker)
            pendingMore.removeValue(forKey: moreKey(asker))
            outcome.reply = digest.text
            outcome.compact = false
            outcome.model = digest.model
            outcome.tokensPerSecond = digest.tokensPerSecond
            outcome.modelCalls = digest.model == nil ? 0 : 1
            outcome.digest = digest
            return outcome

        case .describePhoto:
            reply = "Send a photo to the room first, then ask \(AssistantMention.primary) what is this."

        case .acceptTask:
            guard memory.isAdmin(asker) else {
                reply = "Only an admin device can accept a suggested task. Ask an admin, or say \(AssistantMention.primary) remind me to ..."
                break
            }
            let title = IntentParser.deriveTitle(from: plan.taskTitle ?? text)
            let task = memory.addTask(title: title, assignee: nil, assigneeDevice: nil, due: nil, by: asker, source: "photo")
            taskUpdates.append(task)
            reply = "Task added from the photo check: \(task.shortLine)."

        case .more:
            if let rest = pendingMore.removeValue(forKey: moreKey(asker)) {
                return finish(rest, intent: .more, started: started, tracker: tracker, asker: asker)
            }
            reply = "Nothing more to show."

        case .saveRule, .editRule:
            let title = plan.title ?? IntentParser.deriveTitle(from: plan.body ?? text)
            let change = memory.upsertRule(title: title, body: plan.body ?? text, kind: plan.ruleKind, by: asker)
            switch change {
            case .created(let rule):
                reply = "Saved. Everyone in the room gets a copy."
                ruleUpdates.append(rule)
                rulesUsed = [rule.citation]
            case .updated(let rule):
                reply = "Updated. The older version stays in history."
                ruleUpdates.append(rule)
                rulesUsed = [rule.citation]
            case .unchanged(let rule):
                reply = "That rule already says that."
                rulesUsed = [rule.citation]
            case .denied(let why):
                reply = why
            }

        case .lockRule, .unlockRule:
            let lock = plan.kind == .lockRule
            let change = memory.setLocked(title: plan.title ?? text, locked: lock, by: asker)
            switch change {
            case .updated(let rule):
                reply = lock ? "Locked. Only admins can change it now." : "Unlocked."
                ruleUpdates.append(rule)
                rulesUsed = [rule.citation]
            case .unchanged(let rule), .created(let rule):
                reply = "It was already \(lock ? "locked" : "unlocked")."
                rulesUsed = [rule.citation]
            case .denied(let why):
                reply = why
            }

        case .deleteRule:
            let change = memory.retireRule(title: plan.title ?? text, by: asker)
            switch change {
            case .updated(let tombstone):
                reply = "Deleted \(tombstone.kind.label.lowercased()) \"\(tombstone.title)\". Phones drop it from their copy, and I will not use it in answers."
                ruleUpdates.append(tombstone)
            case .created(let tombstone):
                reply = "No rule called \"\(tombstone.title)\" here, so I told every phone to drop any old copy of it."
                ruleUpdates.append(tombstone)
            case .unchanged(let tombstone):
                reply = "\"\(tombstone.title)\" was already deleted."
                ruleUpdates.append(tombstone)
            case .denied(let why):
                reply = why
            }

        case .addTask:
            let title = IntentParser.deriveTitle(from: plan.taskTitle ?? text)
            if let spoken = plan.assignee?.nilIfBlank,
               !roster.keys.contains(where: { NameMatcher.normalize($0) == NameMatcher.normalize(spoken) }),
               case .ambiguous(let name, let devices) = PeopleDirectory.resolve(spoken, directory: directory) {
                reply = "More than one person is called \(name) (\(devices.joined(separator: ", "))). Which one? Say it again with the device, or ask them to pick distinct names in Settings."
                break
            }
            let who = resolveAssignee(plan.assignee, asker: asker)
            let task = memory.addTask(title: title, assignee: who.name, assigneeDevice: who.device, due: plan.due, by: asker, source: "ask")
            taskUpdates.append(task)
            var line = "Task added: \(task.shortLine)."
            if let device = who.device, device != asker {
                line += " Sent to \(PeopleDirectory.label(for: device, directory: directory))."
            } else if who.name != nil && who.device == nil {
                line += " I do not know \(who.name ?? "them")'s device yet; ask them to open Libre and set their name, or add them to the roster on the Mac."
            }
            reply = line

        case .listMyTasks:
            let mine = memory.tasks(forDevice: asker, roster: roster)
            reply = mine.isEmpty
                ? "You have no open tasks."
                : "Your tasks (\(mine.count)): " + numbered(mine.map { $0.shortLine })

        case .listTeamTasks:
            let open = memory.openTasks
            reply = open.isEmpty
                ? "The team has no open tasks."
                : "Team tasks (\(open.count)): " + numbered(open.map { $0.shortLine })

        case .markDone:
            let ref = plan.taskRef ?? plan.taskTitle ?? text
            if let task = memory.findOpenTask(matching: ref, preferFor: asker, roster: roster) {
                // Owner or admin only (anyone for a task with no owner).
                let names = [directory[asker]].compactMap { $0 }
                guard task.canComplete(by: asker, names: names, isAdmin: memory.isAdmin(asker), roster: roster) else {
                    let owner = task.assigneeDevice.map { PeopleDirectory.label(for: $0, directory: directory) } ?? task.assignee ?? "the owner"
                    reply = "Only \(owner) or an admin can mark \"\(task.title)\" done."
                    break
                }
                if let done = memory.markDone(task.id, by: asker) {
                    reply = "Marked done: \(done.title)."
                    taskUpdates.append(done)
                }
            } else {
                reply = "I could not tell which task. Open tasks: " + numbered(memory.openTasks.prefix(5).map { $0.title })
            }

        case .summarize:
            let window = CatchUp.window(since: since, clearedAt: clearedAt)
            let lines = PromptBudget.trimChat(window.since != nil
                ? memory.recentChat(limit: sinceContextLimit, after: window.floor)
                : memory.recentChat(limit: chatContextLimit, after: window.floor))
            if lines.isEmpty {
                reply = window.since.map { "Nothing new in team chat since \(CatchUp.clock($0))." } ?? "No team chat has reached me yet."
            } else {
                do {
                    let turns: [ChatTurn] = [
                        .system(AssistantPrompts.summarizeSystem),
                        .user(AssistantPrompts.summarizeUser(lines: lines, asker: asker))
                    ]
                    let result = try await llm.chat(turns, json: false, maxTokens: TokenCaps.summarize)
                    tracker.add(result, prompt: turns)
                    reply = CatchUp.header(since: window.since, count: lines.count) + "\n" + result.text
                } catch {
                    return failure(error, intent: .summarize, started: started, tracker: tracker)
                }
            }

        case .takeNotes:
            let source = plan.body ?? text
            do {
                let result = try await llm.chat([
                    .system(AssistantPrompts.notesSystem(people: people)),
                    .user(source)
                ], json: true)
                tracker.add(result)
                guard let notes = IntentParser.decodeNotes(from: result.text) else {
                    reply = "I could not find decisions or action items in that."
                    break
                }
                var created: [TaskItem] = []
                for item in notes.actionItems.prefix(12) {
                    let who = resolveAssignee(item.assignee, asker: asker)
                    created.append(memory.addTask(title: IntentParser.deriveTitle(from: item.title), assignee: who.name, assigneeDevice: who.device, due: item.due, by: asker, source: "notes"))
                }
                let note = memory.addNote(title: notes.title, summary: notes.summary, decisions: notes.decisions, taskIDs: created.map { $0.id }, by: asker)
                taskUpdates.append(contentsOf: created)
                rulesUsed = [note.citation]
                var parts = ["Notes saved."]
                if !notes.decisions.isEmpty { parts.append("Decisions: " + notes.decisions.joined(separator: "; ") + ".") }
                if !created.isEmpty { parts.append("Tasks: " + created.map { $0.shortLine }.joined(separator: "; ") + ".") }
                reply = parts.joined(separator: " ")
            } catch {
                return failure(error, intent: .takeNotes, started: started, tracker: tracker)
            }

        case .answer:
            let question = plan.question ?? text
            // Only relevant knowledge goes in (locked rules always), within a token budget.
            let previousTurn = ConversationMemory.uncovered(memory.threadTurns, summary: memory.roomSummary, clearedAt: clearedAt)
                .last { $0.asker == asker }
            let selection = KnowledgeRetriever.select(question: ConversationMemory.retrievalQuery(question, previous: previousTurn),
                                                      rules: memory.rules, notes: memory.notes, glosses: memory.glossMap)
            checked = selection.checkedTitles
            // Knowledge: role filter first (Admins-only documents never rank for members), then
            // BM25 plus embeddings when the model is there, keyword-only otherwise.
            var hits: [LibraryHit] = []
            var libraryNoMatch = false
            let isAdmin = memory.isAdmin(asker)
            if let library, !library.visibleDocuments(isAdmin: isAdmin).isEmpty {
                let query = ConversationMemory.retrievalQuery(question, previous: previousTurn)
                var vector: [Float]? = nil
                if let embedder, library.chunks.contains(where: { $0.embedding != nil }) {
                    vector = try? await embedder.embed([LibrarySearch.queryPrefix + query]).first
                }
                hits = LibrarySearch.retrieve(query, in: library, isAdmin: isAdmin, queryVector: vector)
                libraryNoMatch = hits.isEmpty
                lastLibrarySearch = (hits.count, vector != nil)
                checked += hits.map { "Doc: " + $0.ref.chipLabel }
            } else {
                lastLibrarySearch = (0, false)
            }
            let open = memory.openTasks
            // Lean prompt: the task list only goes in when the question is about tasks or people.
            let withTasks = QuestionRouter.needsTasks(question, taskTitles: open.map { $0.title })
            // Thread context: summary, latest turns verbatim, recalled older lines. Above 75% of
            // num_ctx, compact the oldest turns first; if still too big, trim the thread.
            func build(_ context: ConversationContext) -> [ChatTurn] {
                [
                    .system(AssistantPrompts.answerSystem(withDocuments: !hits.isEmpty)),
                    .user(AssistantPrompts.answerUser(question: question, asker: asker, rules: selection.rules, notes: selection.notes,
                                                      openTasks: open, noRelevantKnowledge: selection.relevantCount == 0 && hits.isEmpty,
                                                      includeTasks: withTasks, conversation: context,
                                                      documents: hits, libraryNoMatch: libraryNoMatch))
                ]
            }
            var context = conversation(for: question, asker: asker)
            var turns = build(context)
            var compacted = false
            if ConversationMemory.needsCompaction(promptTokens: PromptBudget.tokens(turns) + TokenCaps.answer, context: contextTokens) {
                compacted = await compactThread(tracker: &tracker)
                context = conversation(for: question, asker: asker)
                turns = build(context)
                if ConversationMemory.needsCompaction(promptTokens: PromptBudget.tokens(turns) + TokenCaps.answer, context: contextTokens) {
                    context = conversation(for: question, asker: asker, keep: ConversationMemory.keepAfterCompaction, withRecall: false)
                    turns = build(context)
                }
            }
            let estimate = PromptBudget.tokens(turns) + TokenCaps.answer
            var stats = contextStats[roomKey] ?? ContextStats()
            stats.promptTokens = estimate
            stats.contextTokens = contextTokens
            stats.fill = Double(estimate) / Double(max(1, contextTokens))
            stats.verbatimTurns = context.turns.count
            stats.recalledLines = context.recalled.count
            stats.totalTurns = memory.threadTurns.count
            if compacted { stats.lastCompaction = now() }
            stats.lastCompaction = stats.lastCompaction ?? memory.roomSummary?.updatedAt
            stats.summaryTokens = memory.roomSummary.map { PromptBudget.tokens($0.text) } ?? 0
            stats.summaryTurns = memory.roomSummary?.turnCount ?? 0
            contextStats[roomKey] = stats
            do {
                let result: LLMResult
                if let onPartial, let streaming = llm as? any StreamingLLMClient {
                    result = try await streaming.chatStream(turns, maxTokens: TokenCaps.answer, onDelta: onPartial)
                } else {
                    result = try await llm.chat(turns, json: false, maxTokens: TokenCaps.answer)
                }
                tracker.add(result, prompt: turns)
                // Never pass on a citation that is not in memory: fix versions, flag the rest,
                // then move citations out of the text into chips.
                // [Doc N] tags become chips only for passages that were shown.
                let cited = LibraryCitations.extract(result.text, shown: hits)
                docRefs = cited.refs
                let styled = AnswerStyle.dropContradictedCitations(
                    AnswerStyle.restrict(AnswerStyle.style(cited.text, rules: memory.rules, notes: memory.notes), shown: selection.checkedTitles),
                    noRelevantKnowledge: selection.strongCount == 0 && hits.isEmpty)
                reply = styled.text
                if !docRefs.isEmpty, reply == AnswerStyle.noRuleFallback, cited.text.isEmpty { reply = AnswerStyle.emptyFallback }
                rulesUsed = styled.rulesUsed
                unverifiedRules = styled.unverifiedRules
                noRule = styled.noRule && docRefs.isEmpty
            } catch {
                return failure(error, intent: .answer, started: started, tracker: tracker)
            }
        }

        var outcome = finish(reply, intent: plan.kind, started: started, tracker: tracker, asker: asker)
        outcome.taskUpdates = taskUpdates
        outcome.ruleUpdates = ruleUpdates
        outcome.checked = checked
        outcome.rulesUsed = rulesUsed
        outcome.unverifiedRules = unverifiedRules
        outcome.noRule = noRule
        outcome.docRefs = docRefs
        outcome.skippedClassify = skippedClassify
        return outcome
    }

    // MARK: Helpers

    struct CallTracker {
        var calls = 0
        var model: String?
        var evalCount = 0
        var evalNs: Int64 = 0
        var promptEstimate: Int?
        var promptEval: Int?

        mutating func add(_ result: LLMResult, prompt: [ChatTurn] = []) {
            calls += 1
            model = result.model
            let estimate = PromptBudget.tokens(prompt)
            if estimate >= (promptEstimate ?? 0) {
                promptEstimate = estimate
                promptEval = result.promptEvalCount
            }
            if let c = result.evalCount, let d = result.evalDurationNs {
                evalCount += c
                evalNs += d
            }
        }

        var tokensPerSecond: Double? {
            guard evalNs > 0 else { return nil }
            return Double(evalCount) / (Double(evalNs) / 1_000_000_000)
        }
    }

    private func numbered(_ items: [String]) -> String {
        items.enumerated().map { "\($0.offset + 1)) \($0.element)" }.joined(separator: " ")
    }

    private func finish(_ text: String, intent: IntentKind, started: Date, tracker: CallTracker, asker: String) -> AssistantOutcome {
        let parts = Compactor.split(text)
        if let rest = parts.rest {
            pendingMore[moreKey(asker)] = rest
        } else {
            pendingMore.removeValue(forKey: moreKey(asker))
        }
        var outcome = AssistantOutcome(
            intent: intent,
            reply: parts.first,
            compact: parts.rest != nil,
            model: tracker.model,
            latencyMs: Int((Date().timeIntervalSince(started) * 1000).rounded()),
            tokensPerSecond: tracker.tokensPerSecond,
            evalCount: tracker.calls > 0 ? tracker.evalCount : nil,
            modelCalls: tracker.calls,
            taskUpdates: [],
            ruleUpdates: [],
            error: nil,
            promptTokensEstimate: tracker.promptEstimate,
            promptEvalCount: tracker.promptEval
        )
        outcome.fullReply = text
        outcome.evalTokens = tracker.calls > 0 ? tracker.evalCount : nil
        return outcome
    }

    private func failure(_ error: Error, intent: IntentKind, started: Date, tracker: CallTracker) -> AssistantOutcome {
        let message = (error as? LLMError)?.errorDescription ?? error.localizedDescription
        return AssistantOutcome(
            intent: intent,
            reply: message,
            compact: false,
            model: tracker.model,
            latencyMs: Int((Date().timeIntervalSince(started) * 1000).rounded()),
            tokensPerSecond: tracker.tokensPerSecond,
            evalCount: nil,
            modelCalls: tracker.calls,
            taskUpdates: [],
            ruleUpdates: [],
            error: message,
            promptTokensEstimate: tracker.promptEstimate,
            promptEvalCount: tracker.promptEval
        )
    }
}

/// "What did I miss": since the asker was away when the phone says so, otherwise a recap of the
/// latest lines. A clear-timeline watermark on the Mac always wins.
public enum CatchUp {
    public struct Window: Equatable, Sendable {
        /// The asker's away time, when known (shown in the reply).
        public var since: Date?
        /// Read chat strictly after this time.
        public var floor: Date?
    }

    public static func window(since: Date?, clearedAt: Date?) -> Window {
        Window(since: since, floor: CacheSync.latest(since, clearedAt))
    }

    public static func header(since: Date?, count: Int) -> String {
        if let since { return "New since \(clock(since)):" }
        return "Recap of the last \(count) team message\(count == 1 ? "" : "s"):"
    }

    public static func clock(_ date: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "h:mm a"
        return f.string(from: date)
    }
}

